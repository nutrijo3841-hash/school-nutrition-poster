export function searchIngredients(query = "", category = "전체") {
  return INGREDIENTS_DATABASE.filter(item => {
    const matchesCategory = category === "전체" || item.category === category;
    const cleanQuery = query.trim().toLowerCase();
    const matchesQuery = !cleanQuery || 
      item.name.toLowerCase().includes(cleanQuery) ||
      item.englishName.toLowerCase().includes(cleanQuery) ||
      (item.originInfo && (item.originInfo.etymology.includes(cleanQuery) || item.originInfo.history.includes(cleanQuery))) ||
      item.elementary.catchphrase.toLowerCase().includes(cleanQuery) ||
      item.nutrients.some(n => n.name.toLowerCase().includes(cleanQuery));
    return matchesCategory && matchesQuery;
  });
}

export function getSeasonalIngredients(month) {
  return INGREDIENTS_DATABASE.filter(item => item.peakMonths.includes(month));
}
